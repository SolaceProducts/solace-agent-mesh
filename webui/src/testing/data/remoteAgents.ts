import type { RemoteAgent } from "@/types";

function createRemoteAgent(overrides: Partial<RemoteAgent> & Pick<RemoteAgent, "id" | "name" | "agentUrl" | "agentAuthType" | "createdBy">): RemoteAgent {
    return {
        agentCardLocation: "well_known",
        agentCardUrl: `${overrides.agentUrl}/.well-known/agent-card.json`,
        requestTimeoutSeconds: 60,
        updatedBy: "system",
        createdAt: "2026-01-29T10:00:00.000000+00:00",
        updatedAt: "2026-01-29T10:00:00.000000+00:00",
        ...overrides,
    };
}

