    Array.from({ length: count }, (_, i) => ({
        id: `generated-skill-${String(i).padStart(2, "0")}`,
        name: `Skill_${String(i).padStart(2, "0")}`,
        description: `Auto-generated skill number ${i} for testing.`,
        tags: null,
        origin: "user",
        discoveryStatus: "ready" as const,
        hasReferences: false,
        hasAssets: false,
        hasTools: false,
        resourceCount: 0,
        referenceCount: 0,
        assetCount: 0,
        agents: i % 3 === 0 ? [{ id: `agent-${i}`, name: `Agent ${i}` }] : [],
        createdBy: `user${i}@example.com`,
        updatedBy: `user${i}@example.com`,
        createdAt: "2026-01-01T00:00:00Z",
        updatedAt: "2026-01-01T00:00:00Z",
    }));
