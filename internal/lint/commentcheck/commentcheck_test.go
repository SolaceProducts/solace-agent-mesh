package commentcheck

import (
	"testing"
)

const (
	goDirectives = "//go:build linux\n\npackage x\n\nimport _ \"embed\"\n\n//go:embed a.txt\nvar a string\n\nfunc f() {\n\t_ = a //nolint:errcheck // reason\n\t//logkeys:allow\n\t//line a.go:1\n}\n"
	goStrings    = "package x\n\nvar s = \"http://host\" + `/* no */`\n"
	goGenerated  = "// Code generated by gen. DO NOT EDIT.\n\npackage x\n\n// Doc stays.\nvar v = 1\n"
)

func TestFix(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		path string
		in   string
		want string
	}{
		{
			name: "go doc, in-body, trailing and block comments are removed",
			path: "internal/x/x.go",
			in:   "// Package x does things.\npackage x\n\n// F is exported.\nfunc F() int {\n\t// explain\n\tv := 1 // trailing\n\t/* block */\n\treturn v\n}\n",
			want: "package x\n\nfunc F() int {\n\tv := 1\n\treturn v\n}\n",
		},
		{
			name: "go directives survive",
			path: "internal/x/x.go",
			in:   goDirectives,
			want: goDirectives,
		},
		{
			name: "go cgo preamble survives",
			path: "internal/x/x.go",
			in:   "package x\n\n// #include <stdio.h>\nimport \"C\"\n\n// gone\nvar v = 1\n",
			want: "package x\n\n// #include <stdio.h>\nimport \"C\"\n\nvar v = 1\n",
		},
		{
			name: "go comment markers inside strings are untouched",
			path: "internal/x/x.go",
			in:   goStrings,
			want: goStrings,
		},
		{
			name: "go generated file is untouched",
			path: "internal/x/x_gen.go",
			in:   goGenerated,
			want: goGenerated,
		},
		{
			name: "public sdk keeps exported docs and loses the rest",
			path: "pkg/samtoolsdk/x.go",
			in:   "// Package samtoolsdk is the SDK.\npackage samtoolsdk\n\n// T is a tool.\ntype T struct {\n\t// Name is shown.\n\tName string\n\t// hidden\n\tid string\n}\n\n// F runs.\nfunc F() {\n\t// inside\n}\n\n// f is private.\nfunc f() {}\n\ntype c struct{}\n\n// Close is not public.\nfunc (c) Close() {}\n",
			want: "// Package samtoolsdk is the SDK.\npackage samtoolsdk\n\n// T is a tool.\ntype T struct {\n\t// Name is shown.\n\tName string\n\tid   string\n}\n\n// F runs.\nfunc F() {\n}\n\nfunc f() {}\n\ntype c struct{}\n\nfunc (c) Close() {}\n",
		},
		{
			name: "public sdk tests lose every comment",
			path: "pkg/samtoolsdk/x_test.go",
			in:   "package samtoolsdk\n\n// TestF checks.\nfunc TestF() {}\n",
			want: "package samtoolsdk\n\nfunc TestF() {}\n",
		},
		{
			name: "shell comments go, shebang, directives, strings, expansions and heredocs stay",
			path: "scripts/x.sh",
			in:   "#!/bin/bash\n# about\n# shellcheck disable=SC2086\necho \"a # b\" 'c # d' # trailing\nn=${#arr[@]} $#\ncat <<EOF\n# data\nEOF\n# after\n",
			want: "#!/bin/bash\n# shellcheck disable=SC2086\necho \"a # b\" 'c # d'\nn=${#arr[@]} $#\ncat <<EOF\n# data\nEOF\n",
		},
		{
			name: "python comments go, shebang, directives and string content stay",
			path: "tools/x.py",
			in:   "#!/usr/bin/env python3\n# about\nimport os  # noqa: F401\nx = \"a # b\"  # trailing\ns = \"\"\"\n# kept\n\"\"\"\n",
			want: "#!/usr/bin/env python3\nimport os  # noqa: F401\nx = \"a # b\"\ns = \"\"\"\n# kept\n\"\"\"\n",
		},
		{
			name: "sql comments go, goose directives and strings stay",
			path: "migrations/1.sql",
			in:   "-- +goose Up\n-- explain\nSELECT '--x' /* inline */ FROM t; -- trailing\n/* block\n   more */\n-- +goose Down\n",
			want: "-- +goose Up\nSELECT '--x' FROM t;\n-- +goose Down\n",
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := Fix(tc.path, []byte(tc.in))
			if err != nil {
				t.Fatalf("Fix(%s) error = %v", tc.path, err)
			}
			if string(got) != tc.want {
				t.Errorf("Fix(%s) =\n%s\nwant\n%s", tc.path, got, tc.want)
			}
		})
	}
}

func TestCheckReportsEachCommentLine(t *testing.T) {
	t.Parallel()
	src := "package x\n\n// one\n// two\nfunc f() {\n\t_ = 1 // three\n}\n"
	got, err := Check("internal/x/x.go", []byte(src))
	if err != nil {
		t.Fatalf("Check error = %v", err)
	}
	want := []Violation{
		{Path: "internal/x/x.go", Line: 3, Text: "// one"},
		{Path: "internal/x/x.go", Line: 4, Text: "// two"},
		{Path: "internal/x/x.go", Line: 6, Text: "// three"},
	}
	if len(got) != len(want) {
		t.Fatalf("Check = %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("Check[%d] = %v, want %v", i, got[i], want[i])
		}
	}
}

func TestCheckRejectsUnparsableGo(t *testing.T) {
	t.Parallel()
	if _, err := Check("internal/x/x.go", []byte("package x\nfunc {")); err == nil {
		t.Fatal("Check of invalid Go returned no error")
	}
}

func TestParseAddedLines(t *testing.T) {
	t.Parallel()
	diff := "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -1,0 +2,2 @@\n+x\n+y\n@@ -9 +12 @@\n-z\n+w\n+++ b/b.sh\n@@ -3,1 +3,0 @@\n-gone\n"
	got := parseAddedLines([]byte(diff))
	want := map[string][]int{"a.go": {2, 3, 12}, "b.sh": nil}
	for path, lines := range want {
		if len(got[path]) != len(lines) {
			t.Errorf("added[%s] = %v, want lines %v", path, got[path], lines)
		}
		for _, n := range lines {
			if !got[path][n] {
				t.Errorf("added[%s] missing line %d", path, n)
			}
		}
	}
}

