package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
)

func EmitWorkflowSchema(wf WorkflowDefinitionSchema) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by configapply codegen. DO NOT EDIT.\n//\n")
	buf.WriteString("// Regenerate with: go generate ./internal/configapply/...\n\n")
	buf.WriteString("package codegen\n\n")
	buf.WriteString("// WorkflowSchema is the workflow-shape reference auto-generated\n")
	buf.WriteString("// from internal/workflow/config.go. Consumed by sam config schema\n")
	buf.WriteString("// show workflow and the SKILL emitter; complements SchemaData,\n")
	buf.WriteString("// which describes the wrapper CreateWorkflowRequest DTO.\n")
	buf.WriteString("//\n")
	buf.WriteString("// Adding a new node type: declare a new \"// <Name> node fields.\"-\n")
	buf.WriteString("// style section comment in NodeConfig and re-run go generate.\n")
	buf.WriteString("var WorkflowSchema = WorkflowDefinitionSchema{\n")
	if wf.Description != "" {
		fmt.Fprintf(&buf, "\tDescription: %s,\n", quoteOrBacktick(wf.Description))
	}
	buf.WriteString("\tFields: []FieldSchema{\n")
	for _, f := range wf.Fields {
		emitFieldSchemaLiteralIndented(&buf, f, "\t")
	}
	buf.WriteString(closeBraceLine)

	buf.WriteString("\tNodeTypes: map[string]NodeTypeSchema{\n")
	keys := make([]string, 0, len(wf.NodeTypes))
	for k := range wf.NodeTypes {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		nt := wf.NodeTypes[k]
		fmt.Fprintf(&buf, "\t\t%q: {\n", k)
		fmt.Fprintf(&buf, "\t\t\tNodeType:    %q,\n", nt.NodeType)
		if nt.Description != "" {
			fmt.Fprintf(&buf, "\t\t\tDescription: %s,\n", quoteOrBacktick(nt.Description))
		}
		buf.WriteString("\t\t\tFields: []FieldSchema{\n")
		for _, f := range nt.Fields {
			emitFieldSchemaLiteralIndented(&buf, f, "\t\t\t")
		}
		buf.WriteString("\t\t\t},\n")
		buf.WriteString("\t\t},\n")
	}
	buf.WriteString(closeBraceLine)
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt workflow schema: %w\n--- source ---\n%s", err, buf.String())
	}
	return formatted, nil
}

func emitFieldSchemaLiteralIndented(buf *bytes.Buffer, f FieldSchema, indent string) {
	buf.WriteString(indent + "\t{\n")
	fmt.Fprintf(buf, "%s\t\tJSONName: %q,\n", indent, f.JSONName)
	fmt.Fprintf(buf, "%s\t\tGoType:   %q,\n", indent, f.GoType)
	if f.DisplayTypeOverride != "" {
		fmt.Fprintf(buf, "%s\t\tDisplayTypeOverride: %q,\n", indent, f.DisplayTypeOverride)
	}
	if f.Required {
		buf.WriteString(indent + "\t\tRequired: true,\n")
	}
	if f.MinLen >= 0 {
		fmt.Fprintf(buf, "%s\t\tMinLen:   %d,\n", indent, f.MinLen)
	} else {
		buf.WriteString(indent + "\t\tMinLen:   -1,\n")
	}
	if f.MaxLen >= 0 {
		fmt.Fprintf(buf, "%s\t\tMaxLen:   %d,\n", indent, f.MaxLen)
	} else {
		buf.WriteString(indent + "\t\tMaxLen:   -1,\n")
	}
	if len(f.OneOf) > 0 {
		fmt.Fprintf(buf, "%s\t\tOneOf:    []string{", indent)
		for i, v := range f.OneOf {
			if i > 0 {
				buf.WriteString(", ")
			}
			fmt.Fprintf(buf, "%q", v)
		}
		buf.WriteString("},\n")
	}
	if f.Description != "" {
		fmt.Fprintf(buf, "%s\t\tDescription: %s,\n", indent, quoteOrBacktick(f.Description))
	}
	if f.Secret {
		buf.WriteString(indent + "\t\tSecret:   true,\n")
	}
	if f.Pointer {
		buf.WriteString(indent + "\t\tPointer:  true,\n")
	}
	buf.WriteString(indent + closeBraceLine)
}

const (
	closeBraceLine = "\t},\n"
)
