package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

type SchemaSpec struct {
	Kind       string
	PluralPath string
	Request    StructInfo
	V2Copy     bool
}

func EmitSchemaData(specs []SchemaSpec) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by configapply codegen. DO NOT EDIT.\n")
	buf.WriteString("//\n")
	buf.WriteString("// Regenerate with: go generate ./internal/configapply/...\n\n")
	buf.WriteString("package codegen\n\n")
	buf.WriteString("// SchemaData is the per-kind documentation surface auto-generated from\n")
	buf.WriteString("// the request DTO structs (their fields, validate tags, and Go doc\n")
	buf.WriteString("// comments). Consumed by sam config schema and the SKILL emitter.\n")
	buf.WriteString("//\n")
	buf.WriteString("// Adding a new kind: extend the spec list in the codegen go:generate\n")
	buf.WriteString("// directive. Adding a new field on an existing kind: add a Go doc\n")
	buf.WriteString("// comment for it (optional but recommended) and re-run go generate.\n")
	buf.WriteString("var SchemaData = map[string]KindSchema{\n")
	for _, s := range specs {
		ks := BuildKindSchema(s.Kind, s.PluralPath, s.Request, s.V2Copy)
		fmt.Fprintf(&buf, "\t%q: ", ks.Kind)
		emitKindSchemaLiteral(&buf, ks)
		buf.WriteString(",\n")
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt schema_data: %w\n--- source ---\n%s", err, buf.String())
	}
	return formatted, nil
}

func emitKindSchemaLiteral(buf *bytes.Buffer, ks KindSchema) {
	buf.WriteString("{\n")
	fmt.Fprintf(buf, "\t\tKind:        %q,\n", ks.Kind)
	fmt.Fprintf(buf, "\t\tPluralPath:  %q,\n", ks.PluralPath)
	fmt.Fprintf(buf, "\t\tDescription: %s,\n", quoteOrBacktick(ks.Description))
	buf.WriteString("\t\tFields: []FieldSchema{\n")
	for _, f := range ks.Fields {
		emitFieldSchemaLiteral(buf, f)
	}
	buf.WriteString("\t\t},\n")
	buf.WriteString("\t}")
}

func emitFieldSchemaLiteral(buf *bytes.Buffer, f FieldSchema) {
	buf.WriteString("\t\t\t{\n")
	fmt.Fprintf(buf, "\t\t\t\tJSONName: %q,\n", f.JSONName)
	fmt.Fprintf(buf, "\t\t\t\tGoType:   %q,\n", f.GoType)
	if f.Required {
		buf.WriteString("\t\t\t\tRequired: true,\n")
	}
	if f.MinLen >= 0 {
		fmt.Fprintf(buf, "\t\t\t\tMinLen:   %d,\n", f.MinLen)
	} else {
		buf.WriteString("\t\t\t\tMinLen:   -1,\n")
	}
	if f.MaxLen >= 0 {
		fmt.Fprintf(buf, "\t\t\t\tMaxLen:   %d,\n", f.MaxLen)
	} else {
		buf.WriteString("\t\t\t\tMaxLen:   -1,\n")
	}
	if len(f.OneOf) > 0 {
		buf.WriteString("\t\t\t\tOneOf:    []string{")
		for i, v := range f.OneOf {
			if i > 0 {
				buf.WriteString(", ")
			}
			buf.WriteString(strconv.Quote(v))
		}
		buf.WriteString("},\n")
	}
	if f.Description != "" {
		fmt.Fprintf(buf, "\t\t\t\tDescription: %s,\n", quoteOrBacktick(f.Description))
	}
	if f.Secret {
		buf.WriteString("\t\t\t\tSecret:   true,\n")
	}
	if f.Pointer {
		buf.WriteString("\t\t\t\tPointer:  true,\n")
	}
	buf.WriteString("\t\t\t},\n")
}

func quoteOrBacktick(s string) string {
	if !strings.ContainsRune(s, '`') && strings.ContainsRune(s, '\\') {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}
