package pull

import (
	"bytes"
	"cmp"
	"fmt"
	"maps"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/SolaceProducts/solace-agent-mesh/internal/configapply/manifest"
)

type ResourceRef struct {
	Name   string
	From   string
	Source string
}

func buildManifestYAML(opts Options, entries map[string][]ResourceRef, usedSources map[string]string, platform *platformBlock, c interface{ TargetURL() string }) ([]byte, error) {
	doc := manifestDoc{
		Kind:      "manifest",
		Name:      manifestName(opts.ManifestName),
		Target:    targetBlock{URL: c.TargetURL()},
		Platform:  platform,
		Resources: map[string][]any{},
	}
	if len(usedSources) > 0 {
		doc.Sources = maps.Clone(usedSources)
	}
	for _, k := range pulledKinds {
		plural := pluralKind(k)
		refs, ok := entries[plural]
		if !ok || len(refs) == 0 {
			continue
		}
		sorted := append([]ResourceRef(nil), refs...)
		slices.SortStableFunc(sorted, func(a, b ResourceRef) int { return cmp.Compare(a.Name, b.Name) })
		yamlEntries := make([]any, 0, len(sorted))
		for _, r := range sorted {
			yamlEntries = append(yamlEntries, marshalRef(r))
		}
		doc.Resources[plural] = yamlEntries
	}
	doc.Description = fmt.Sprintf("Generated by `sam config pull` at %s.", timestampSlug())

	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, fmt.Errorf("marshal manifest: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("close encoder: %w", err)
	}
	return buf.Bytes(), nil
}

func marshalRef(r ResourceRef) any {
	if r.Source == "" {
		return r.Name
	}
	from := r.From
	if from == "" {
		from = r.Name
	}
	if from == r.Name {
		return from + "@" + r.Source
	}
	return map[string]string{
		"from": from + "@" + r.Source,
		"as":   r.Name,
	}
}

func manifestName(override string) string {
	if override == "" {
		return "pulled-" + timestampSlug()
	}
	base := override
	if idx := strings.LastIndexAny(base, `/\`); idx >= 0 {
		base = base[idx+1:]
	}
	for _, ext := range []string{".yaml", ".yml"} {
		if cut, ok := strings.CutSuffix(base, ext); ok {
			base = cut
			break
		}
	}
	if base == "" {
		return "pulled-" + timestampSlug()
	}
	return base
}

type manifestDoc struct {
	Kind        string            `yaml:"kind"`
	Name        string            `yaml:"name"`
	Description string            `yaml:"description,omitempty"`
	Target      targetBlock       `yaml:"target"`
	Sources     map[string]string `yaml:"sources,omitempty"`
	Platform    *platformBlock    `yaml:"platform,omitempty"`
	Resources   map[string][]any  `yaml:"resources,omitempty"`
}

type targetBlock struct {
	URL string `yaml:"url"`
}

type platformBlock struct {
	ProfileProvider *profileProviderBlock `yaml:"profileProvider,omitempty"`
	DefaultRoles    *defaultRolesBlock    `yaml:"defaultRoles,omitempty"`

	WebuiSettings *manifest.WebuiSettingsSpec `yaml:"webuiSettings,omitempty"`
}

type profileProviderBlock struct {
	Toolset string `yaml:"toolset"`
	Claim   string `yaml:"claim,omitempty"`
}

type defaultRolesBlock struct {
	Roles []string `yaml:"roles"`
}
